# 장애물 여부 판정 함수
def is_obstacle(x, y):
    if y < 0 or y >= len(raw_map):
        return True
    if x < 0 or x >= len(raw_map[0]):
        return True

    return raw_map[y][x] == '@'


# ===============================
#   메인 루프 (입력 받아 처리)
# ===============================
print("좌표 장애물 판정기 시작! (종료: q)")
print("형식: x y (예: 6 2)")

while True:
    user_input = input("좌표 입력: ")

    if user_input.lower() == "q":
        print("종료합니다.")
        break

    try:
        x, y = map(int, user_input.split())
    except:
        print("입력 형식 오류! 예: 5 3")
        continue

    if is_obstacle(x, y):
        print(f"→ ({x}, {y}) 는 장애물(@) 입니다!")
    else:
        print(f"→ ({x}, {y}) 는 빈칸(.) 입니다!")
